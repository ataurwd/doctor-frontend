const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBanglaDigits(val) {
  return String(val ?? '').replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]);
}

export function toEnglishDigits(val) {
  let str = String(val ?? '');
  BN_DIGITS.forEach((bn, idx) => {
    str = str.split(bn).join(String(idx));
  });
  return str;
}

export function digits(val, locale = 'en') {
  return locale === 'bn' ? toBanglaDigits(val) : String(val ?? '');
}

export function t(locale = 'en', path = '', replacements = {}) {
  const lang = locale === 'bn' ? 'bn' : 'en';
  const parts = path.split('.');
  let cur = DICTIONARY[lang];
  for (const p of parts) {
    cur = cur?.[p];
  }
  if (cur === undefined) return path;
  if (typeof cur !== 'string') return cur;
  let result = cur;
  for (const [k, v] of Object.entries(replacements)) {
    result = result.replaceAll(`:${k}`, String(v ?? ''));
  }
  return result;
}

export function tr(item, field, locale = 'en') {
  if (!item) return '';
  const obj = item[field];
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  const val = obj[locale];
  if (val && String(val).trim() !== '') return val;
  return obj.en || '';
}

export function trList(item, field, locale = 'en') {
  if (!item) return [];
  const obj = item[field];
  if (!obj) return [];
  if (Array.isArray(obj)) return obj;
  const list = obj[locale];
  if (Array.isArray(list) && list.filter(Boolean).length > 0) return list;
  return Array.isArray(obj.en) ? obj.en : [];
}

export function usesFallback(item, fields = ['title', 'summary', 'what_it_is', 'body'], locale = 'en') {
  if (locale !== 'bn' || !item) return false;
  for (const f of fields) {
    const obj = item[f];
    if (!obj || typeof obj !== 'object') continue;
    const enVal = obj.en;
    const bnVal = obj.bn;
    const hasEn = Array.isArray(enVal) ? enVal.length > 0 : Boolean(enVal && String(enVal).trim());
    const hasBn = Array.isArray(bnVal) ? bnVal.length > 0 : Boolean(bnVal && String(bnVal).trim());
    if (hasEn && !hasBn) return true;
  }
  return false;
}

export function settingLocalized(settings = {}, baseKey, locale = 'en', fallback = '') {
  const key = `${baseKey}_${locale === 'bn' ? 'bn' : 'en'}`;
  return settings[key] || settings[`${baseKey}_en`] || fallback;
}

export function telHref(phone) {
  if (!phone) return '#';
  let d = toEnglishDigits(phone).replace(/\D+/g, '');
  if (d.startsWith('0')) {
    d = `88${d}`;
  }
  return `tel:+${d}`;
}

export function whatsappHref(settings = {}) {
  const raw = settings.whatsapp_number || '';
  const d = toEnglishDigits(raw).replace(/\D+/g, '');
  if (!d) return null;
  const normalized = d.startsWith('0') ? `88${d}` : d;
  const msg = encodeURIComponent(
    settings.whatsapp_message || 'Hello, I would like to request an appointment with Dr. Sajib.'
  );
  return `https://wa.me/${normalized}?text=${msg}`;
}

export function formatDate(dateStr, locale = 'en') {
  if (!dateStr) return '';
  const d = new Date(dateStr);
  if (Number.isNaN(d.getTime())) return '';
  const formatted = d.toLocaleDateString(locale === 'bn' ? 'bn-BD' : 'en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });
  return digits(formatted, locale);
}

